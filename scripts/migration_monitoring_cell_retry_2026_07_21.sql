        CHECK (keyword_source IN ('confirmed', 'contract', 'extra')),
    CONSTRAINT chk_monitoring_run_cells_platform
        CHECK (platform IN ('dashscope', 'deepseek', 'kimi', 'doubao')),
    CONSTRAINT chk_monitoring_run_cells_state
        CHECK (state IN (
            'queued', 'running', 'succeeded', 'failed', 'pending_identity',
