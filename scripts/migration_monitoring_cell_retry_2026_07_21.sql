        UNIQUE (task_id, keyword_source, keyword_id, platform),
    CONSTRAINT uq_monitoring_run_cells_retry_scope
        UNIQUE (id, task_id, brand_id, plan_hash),
    CONSTRAINT fk_monitoring_run_cells_task
        FOREIGN KEY (task_id) REFERENCES public.monitoring_tasks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_monitoring_run_cells_task_brand
        FOREIGN KEY (task_id, brand_id)
        REFERENCES public.monitoring_tasks(id, brand_id) ON DELETE RESTRICT,
    CONSTRAINT fk_monitoring_run_cells_brand
        FOREIGN KEY (brand_id) REFERENCES public.brands(id) ON DELETE RESTRICT,
    CONSTRAINT fk_monitoring_run_cells_quote_brand
        FOREIGN KEY (quote_id, brand_id)
        REFERENCES public.quotes(id, brand_id) ON DELETE RESTRICT,
