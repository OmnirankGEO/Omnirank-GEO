        CHECK (attempt_count >= 0 AND retry_count >= 0 AND retry_count <= attempt_count),
    CONSTRAINT chk_monitoring_run_cells_json
        CHECK (
            pg_catalog.jsonb_typeof(entitlement_snapshot) = 'object'
            AND pg_catalog.jsonb_typeof(order_snapshot) = 'object'
        ),
    CONSTRAINT chk_monitoring_run_cells_plan_shape
        CHECK (
            is_planned
            OR (NOT is_planned AND state = 'unavailable')
        ),
    CONSTRAINT chk_monitoring_run_cells_result_terminal
        CHECK (
            (state IN ('succeeded', 'pending_identity') AND result_id IS NOT NULL)
            OR (state NOT IN ('succeeded', 'pending_identity') AND result_id IS NULL)
        ),
    CONSTRAINT chk_monitoring_run_cells_claim
        CHECK (
            (state = 'running' AND claim_token IS NOT NULL AND claim_until IS NOT NULL)
            OR (state <> 'running' AND claim_token IS NULL AND claim_until IS NULL)
        )
);

