-- Durable word x platform execution plan and covered single-cell retry ledger.
-- Additive/idempotent. It never changes billing prices, balances, or feature flags.
SET LOCAL search_path = pg_catalog, public;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint
         WHERE conrelid = 'public.monitoring_tasks'::regclass
           AND conname = 'uq_monitoring_tasks_id_brand'
    ) THEN
        ALTER TABLE public.monitoring_tasks
            ADD CONSTRAINT uq_monitoring_tasks_id_brand UNIQUE (id, brand_id);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint
         WHERE conrelid = 'public.quotes'::regclass
           AND conname = 'uq_quotes_id_brand'
    ) AND pg_catalog.to_regclass('public.ux_quotes_id_brand') IS NULL THEN
        -- The quote snapshot migration (earlier in the unified manifest)
        -- already creates an exact non-partial unique btree on this key.
        -- Reuse it as the FK authority instead of scanning/locking quotes to
        -- build a second equivalent unique object.
        ALTER TABLE public.quotes
            ADD CONSTRAINT uq_quotes_id_brand UNIQUE (id, brand_id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint
         WHERE conrelid = 'public.monitoring_results'::regclass
           AND conname = 'uq_monitoring_results_id_task'
    ) THEN
        ALTER TABLE public.monitoring_results
            ADD CONSTRAINT uq_monitoring_results_id_task UNIQUE (id, task_id);
    END IF;
END $$;

