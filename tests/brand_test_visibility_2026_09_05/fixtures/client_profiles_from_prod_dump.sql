CREATE TABLE IF NOT EXISTS public.client_profiles (
    id text NOT NULL,
    name text NOT NULL,
    industry text,
    business text,
    products text,
    target_users text,
    pain_points text,
    competitors text,
    persona_positioning text,
    persona_tone text,
    persona_catchphrases text,
    persona_background text,
    persona_golden_quotes text,
    target_platforms text,
    successful_patterns text,
    negative_feedback text,
    brand_constraints text,
    is_deleted integer DEFAULT 0,
    deleted_at timestamp without time zone,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    company_intro text,
    core_value text,
    selling_points text,
    success_cases text,
    testimonials text,
    brand_id integer,
    story_type text,
    differentiation text,
    content_direction text,
    business_summary text,
    business_misunderstandings text,
    knowledge_files text,
    brand_display_names text,
    visual_style text DEFAULT ''::text,
    content_pillars text DEFAULT '[]'::text,
    structured_knowledge text,
    personality_profile text,
    creator_type character varying(50),
    content_frequency character varying(50),
    monetization_goal character varying(50),
    follower_count character varying(50),
    profile_completeness jsonb DEFAULT '{}'::jsonb,
    preferred_advisor_id text,
    plan_mode character varying(20) DEFAULT 'inspiration'::character varying,
    admin_insight text,
    admin_insight_level character varying(20),
    admin_insight_updated_at timestamp without time zone,
    share_code character varying(20),
    category character varying(100),
    industry_brief jsonb,
    industry_brief_status character varying(20),
    industry_brief_started_at timestamp without time zone,
    preferred_expert_id text,
    industry_brief_confirmed boolean DEFAULT false,
    industry_brief_confirmed_at timestamp without time zone,
    industry_brief_partial_fields jsonb,
    industry_brief_edits jsonb,
    industry_brief_version integer DEFAULT 0,
    service_scope character varying(20),
    service_scope_reasoning text,
    local_competitors jsonb DEFAULT '[]'::jsonb,
    brief_applied_version integer DEFAULT 0,
    brief_applied_at timestamp without time zone,
    business_type character varying(20) DEFAULT 'B2C'::character varying,
    city_scope character varying(20) DEFAULT 'local'::character varying,
    social_fields jsonb DEFAULT '{}'::jsonb,
    contact_phone text,
    contact_wechat text,
    contact_website text,
    contact_address text,
    organization_id bigint,
    created_by_user_id integer,
    created_by_membership_id bigint,
    created_by_actor_kind text,
    responsible_user_id integer,
    artifact_visibility text,
    archived_with_brand_at timestamp with time zone,
    CONSTRAINT org_client_profiles_shape CHECK (((organization_id IS NULL) OR ((created_by_actor_kind = ANY (ARRAY['owner'::text, 'member'::text, 'system'::text])) AND (created_by_user_id IS NOT NULL) AND (responsible_user_id IS NOT NULL) AND (artifact_visibility = ANY (ARRAY['private'::text, 'team'::text, 'external'::text])) AND ((created_by_actor_kind <> 'member'::text) OR (created_by_membership_id IS NOT NULL)))))
);
