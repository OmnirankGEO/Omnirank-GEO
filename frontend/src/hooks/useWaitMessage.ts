/**
 * v1_3 (CTO-15.1 2026-04-19) 节奏公式
 *
 * 学术依据（HCI 共识）:
 *   - Nielsen (1993): 10s 是用户注意力上限 → 8s 封顶避免"卡死感"
 *   - Miller (1968): conversational feedback < 2s → 下限保护避免"闪跳"
 *   - Shneiderman: 不规则节奏比固定间隔更像真人思考
 *
 * 2026-04-19 老板反馈 "GEO 方案 1s 两跳太快" → 去掉前 15s 3-5s 密集段，
 * 统一 3-8s 随机（下限提到 3s，和老板早前"3-8s"原话对齐）
 *
 * @param _startTimeMs 本轮 active 开始的时间戳（保留参数兼容调用方，目前未用）
 */
function calcRotateInterval(_startTimeMs: number): number {
  // 全程 3-8s 随机（不分段，稳定体感）
  return 3000 + Math.random() * 5000;
}

