export type WaitScene = keyof typeof MESSAGES;

/** 阶段化等待文案 — 按 elapsed 秒数推进到不同 stage, stage 内部仍随机抽 */
export interface WaitStage {
  /** 这个阶段持续到 elapsed 多少秒为止 (不含, 下一 stage 开始) */
  untilSec: number;
  /** 这个阶段的文案池 */
  messages: readonly string[];
}

/**
 * 按时间轴推进的安抚文案 — 模拟"真实进度"体感
 *
 * 用法: 用于后端单次 POST 无法实时推进度的长任务, 但我们知道内部有明确阶段
 *   const msg = useStagedWaitMessage(loading, [
 *     { untilSec: 5, messages: ['识别品牌信息...', '分析行业...'] },
 *     { untilSec: 25, messages: ['调用 5118 扩词...', '做地域下钻...'] },
 *     { untilSec: 50, messages: ['评估竞争度...', '算价...'] },
 *     { untilSec: Infinity, messages: ['快好了, 做最后整理...'] },
 *   ])
 *
 * 比纯随机的 useWaitMessage 更"像真的", 且零改动后端就能实现"看起来有进度感".
 */
export function useStagedWaitMessage(
  active: boolean,
  stages: WaitStage[],
): string | null {
  const [index, setIndex] = useState(-1);
  const [elapsed, setElapsed] = useState(0);
  const startTimeRef = useRef(0);

  // 计时器 (每秒 tick)
  useEffect(() => {
    if (!active) {
      setElapsed(0);
      return;
    }
    startTimeRef.current = Date.now();
    const t = setInterval(() => setElapsed(e => e + 1), 1000);
    return () => clearInterval(t);
  }, [active]);

  // 找当前 stage (untilSec 升序, 第一个大于 elapsed 的)
  const currentStage = stages.find(s => elapsed < s.untilSec) ?? stages[stages.length - 1];

  // v1_3 (CTO-15.1 2026-04-19): 节奏改 calcRotateInterval (前 15s 3-5s / 15s 后 4-8s)
  // stage 边界不动 (那是对齐后端的真实进度), 只改 stage 内部轮换节奏
  useEffect(() => {
    if (!active || !currentStage || currentStage.messages.length === 0) {
      setIndex(-1);
      return;
    }
    const pool = currentStage.messages;
    const timers: ReturnType<typeof setTimeout>[] = [];

    const pickNext = (prev: number): number => {
      if (pool.length <= 1) return 0;
      let next = Math.floor(Math.random() * pool.length);
      let retry = 0;
      while (next === prev && retry < 4) {
        next = Math.floor(Math.random() * pool.length);
        retry++;
      }
      return next;
    };

    // v1_3 (CTO-15.1 2026-04-19) 老板反馈 1s 两跳：
    // 原 stage 切换"立即换一条" 叠加 3-5s 密集 → 边界瞬间视觉跳跃
    // 改为 stage 切换延迟 1.5s 首次换（让上一 stage 最后一条有呼吸感）
    // 首次 mount（上一条 index=-1）也走延迟路径，但下限更短（0.8s）
    const isFirstMount = index < 0;
    const firstDelay = isFirstMount
      ? 800 + Math.random() * 700          // 首次 mount: 0.8-1.5s
      : 1500 + Math.random() * 800;        // stage 切换: 1.5-2.3s
    const scheduleNext = () => {
      timers.push(
        setTimeout(() => {
          setIndex(prev => pickNext(prev));
          scheduleNext();
        }, calcRotateInterval(startTimeRef.current)),
      );
    };
    timers.push(
      setTimeout(() => {
        setIndex(prev => pickNext(prev));
        scheduleNext();
      }, firstDelay),
    );

    return () => {
      timers.forEach(t => clearTimeout(t));
    };
    // 依赖 currentStage 而非 stages, 让 stage 切换触发重置
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [active, currentStage]);

  if (!currentStage || currentStage.messages.length === 0) return null;
  return index >= 0 ? currentStage.messages[index] : null;
}

export function useWaitMessage(active: boolean, scene: WaitScene = 'thinking'): string | null {
  const pool = MESSAGES[scene] || MESSAGES.thinking;
  const [index, setIndex] = useState(-1); // -1 = 不显示
  const startTimeRef = useRef(0);

  useEffect(() => {
    if (!active) {
      setIndex(-1);
      return;
    }
    startTimeRef.current = Date.now();
    const timers: ReturnType<typeof setTimeout>[] = [];

    const pickNext = (prev: number): number => {
      if (pool.length <= 1) return 0;
      let next = Math.floor(Math.random() * pool.length);
      let retry = 0;
      while (next === prev && retry < 4) {
        next = Math.floor(Math.random() * pool.length);
        retry++;
      }
      return next;
    };

    // v1_3 (CTO-15.1 2026-04-19): 首条延迟走 calcRotateInterval 同公式 (前 15s 3-5s)
    // 对话气泡立即有 step.message "正在..." 显示, rotating 作为副标题可以稍晚
    const firstDelay = calcRotateInterval(startTimeRef.current);

    timers.push(
      setTimeout(() => {
        setIndex(pickNext(-1));
        const scheduleNext = () => {
          timers.push(
            setTimeout(() => {
              setIndex(prev => pickNext(prev));
              scheduleNext();
            }, calcRotateInterval(startTimeRef.current)),
          );
        };
        scheduleNext();
      }, firstDelay),
    );

    return () => {
      timers.forEach(t => clearTimeout(t));
    };
  }, [active, pool]);

  return index >= 0 ? pool[index] : null;
}
