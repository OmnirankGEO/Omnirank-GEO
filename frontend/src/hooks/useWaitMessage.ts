/**
 * useWaitMessage — 通用长任务"安抚文字"轮换 hook
 *
 * 场景: 某个异步任务等待 > 几秒时, 避免 UI 显示死文字让用户觉得"系统没动".
 * 设计:
 *   - 每个业务场景有自己的文案池 (口语化自言自语, 非"正在..."机械式)
 *   - 首条延迟 4-6 秒随机, 后续每条间隔 4-7 秒随机 (不整齐)
 *   - 随机抽取不重复 (最多重试 4 次避免连续同句)
 *
 * 用法:
 *   const msg = useWaitMessage(loading, 'estimate')
 *   return (
 *     <div>
 *       <Loader2 className="animate-spin" />
 *       <span>{msg || '正在加载...'}</span>
 *     </div>
 *   )
 */

