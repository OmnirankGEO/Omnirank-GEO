/**
 * 用**任意一张**分类表做匹配 —— 抽成参数是为了让判据能喂一张
 * **故意造出碰撞**的合成表,从而**真的验到「最长优先」这条规则本身**。
 *
 * 🔴 为什么非抽不可:注毒实测,把下面的 `.sort()` 撤掉,15 格判据**一格都不红** ——
 *    因为单字去掉之后,现表里已经没有跨类子串碰撞,表顺序与最长优先**结果相同**。
 *    也就是说这条规则**在今天的表上是冗余的**,它防的是**将来**新增的词。
 *    冗余不等于可以不验:**没有判据能看见的修法,和没做过一样**,
 *    下一个人重构时会顺手把它删掉,而那一刻所有格子仍然全绿。
 */
export function classifyWith(
    categories: readonly IndustryCategory[],
    raw: string | undefined | null,
    fallback: 'raw' | '其他' = 'raw',
): string {
    if (!raw) return '其他';
    const text = raw.toLowerCase();
    const index = categories
        .flatMap((cat) => cat.keywords.map((kw) => ({ kw: kw.toLowerCase(), label: cat.label })))
        /* 🔴 本单的核心:顺序由**关键词长度**定,不由分类在表里的位置定。
              等长时才退回表顺序(稳定排序)。 */
        .sort((a, b) => b.kw.length - a.kw.length);
    for (const { kw, label } of index) {
        if (text.includes(kw)) return label;
    }
    return fallback === '其他' ? '其他' : raw;
}

/**
 * 把自由文本行业归类到标准分类。
 *
 * @param fallback 匹配不上时返回什么。
 *   · `'raw'`(默认)= 保留原文,不强制归类 —— `lib` 原有行为;
 *   · `'其他'` = OnlineQuoteFlow 原有行为。
 * 🔴 **两份表合一不等于两处行为合一**:兜底不同是真实差异,
 *    合表时把它做成参数,让两个调用点各自保持原行为 ——
 *    否则「统一一下」会顺手改掉一处没人要求改的行为。
 */
export function normalizeIndustry(
    raw: string | undefined | null,
    fallback: 'raw' | '其他' = 'raw',
): string {
    return classifyWith(INDUSTRY_CATEGORIES, raw, fallback);
}
