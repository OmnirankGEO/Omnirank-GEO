# Token使用追踪器（用于累计单次诊断的Token消耗）
class TokenTracker:
    """追踪单次任务的Token使用"""

    _instance = None

    def __init__(self):
        self.reset()

    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def reset(self):
        self.total_input = 0
        self.total_output = 0
        self.call_count = 0
        self.diagnosis_id = None
        self.model_name = None

    def add(self, input_tokens: int, output_tokens: int, model_name: str | None = None):
        self.total_input += input_tokens
        self.total_output += output_tokens
        self.call_count += 1
        if model_name:
            self.model_name = model_name

    def set_diagnosis_id(self, diagnosis_id: int):
        self.diagnosis_id = diagnosis_id

    def save_to_db(self, task_type: str = "diagnosis_report"):
        """保存累计Token到数据库"""
        if self.call_count == 0:
            return
        try:
            from db.diagnosis_db import save_token_usage
            import uuid

            save_token_usage(
                task_id=f"diag_{uuid.uuid4().hex[:8]}",
                model_name=self.model_name or DEEPSEEK_OFFICIAL_FLASH,
                input_tokens=self.total_input,
                output_tokens=self.total_output,
                operation_type=task_type,
                diagnosis_id=self.diagnosis_id,
            )
            print(
                f"  💾 Token使用已记录: {self.total_input + self.total_output} tokens, {self.call_count}次调用"
            )
        except Exception as e:
            print(f"  ⚠️ Token保存失败: {e}")


async def call_llm(
    system_prompt: str,
    user_message: str,
    temperature: float = 0.7,
    max_tokens: int = 4000,
    track_tokens: bool = True,  # 新增：是否追踪Token
) -> str:
    """调用 LLM API (支持 DeepSeek 或 OpenRouter Gemini)"""
    import os

    if REPORT_LLM_PROVIDER == "openrouter_gemini":
        # 使用 OpenRouter Gemini 3 Pro
        api_key = os.getenv("OPENROUTER_API_KEY", "")
        if not api_key:
            # 回退：从 settings.json 读取
            try:
                from config.settings_manager import get_current_settings
                api_key = get_current_settings().openrouter_api_key or ""
            except Exception:
                pass
        if not api_key:
            return "[LLM未配置] 请在设置页面配置 OpenRouter API Key"

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "HTTP-Referer": "https://omnirank.cn",
            "X-Title": "GEO Report Generator",
        }

        payload = {
            "model": OPENROUTER_MODEL,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        try:
            async with httpx.AsyncClient(timeout=180.0) as client:
                response = await client.post(
                    OPENROUTER_API_URL, headers=headers, json=payload
                )
                response.raise_for_status()
                result = response.json()

                # 追踪Token使用
                if track_tokens:
                    usage = result.get("usage", {})
                    TokenTracker.get_instance().add(
                        usage.get("prompt_tokens", 0),
                        usage.get("completion_tokens", 0),
                        model_name=OPENROUTER_MODEL,
                    )

                return result["choices"][0]["message"]["content"]
        except Exception as e:
            return f"[OpenRouter LLM调用失败] {str(e)}"

    else:
        # 默认使用 DeepSeek
        api_key = os.getenv("DEEPSEEK_API_KEY", DEEPSEEK_API_KEY)
        if not api_key:
            # 回退：从 settings.json 读取
            try:
                from config.settings_manager import get_current_settings
                api_key = get_current_settings().deepseek_api_key or ""
            except Exception:
                pass
        if not api_key:
            return "[LLM未配置] 请在设置页面配置 DeepSeek API Key"

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }

        payload = {
            "model": DEEPSEEK_MODEL,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        try:
            async with httpx.AsyncClient(timeout=120.0) as client:
                response = await client.post(
                    DEEPSEEK_API_URL, headers=headers, json=payload
                )
                response.raise_for_status()
                result = response.json()

                # 追踪Token使用
                if track_tokens:
                    usage = result.get("usage", {})
                    TokenTracker.get_instance().add(
                        usage.get("prompt_tokens", 0),
                        usage.get("completion_tokens", 0),
                        model_name=DEEPSEEK_MODEL,
                    )

                return result["choices"][0]["message"]["content"]
        except Exception as e:
            return f"[DeepSeek LLM调用失败] {str(e)}"


