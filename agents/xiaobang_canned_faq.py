def match_canned_faq(query: str) -> XiaobangCannedFAQ | None:
    """关键词组合命中检测 · 命中即返硬 FAQ · 否则 None

    判定:任一 pattern(内层 list)的所有 token 都在 query 里 → 命中
    顺序敏感:列表前面的 FAQ 优先
    """
    if not query:
        return None
    q = query.lower()
    for faq in CANNED_FAQS:
        for pattern in faq.patterns:
            # pattern 是 list[str] · 所有 token 都在 query 里才算命中
            if all(tok.lower() in q for tok in pattern):
                return faq
    return None
