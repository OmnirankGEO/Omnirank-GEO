# V10 增强验证函数
# ============================================
def validate_article_v10(content: str, brand_name: str = None) -> tuple:
    """
    V10 增强验证：在 V9 基础上增加 GEO 信号检查和客观性检查

    Args:
        content: 文章内容
        brand_name: 客户品牌名（可选，用于验证排名位置）

    Returns:
        (score, issues) - 分数和问题列表
    """
    import re

    score = 100
    issues = []

    # ============================================
    # 一、结构完整性检查（每项 -5）
    # ============================================

    # 利益披露 / 研究说明
    if "研究说明" not in content and "利益披露" not in content and "独立研究" not in content:
        score -= 5
        issues.append("[结构] 缺少利益披露或研究说明")

    # 评分模型
    if "综合评分" not in content and "评分模型" not in content and "5维度" not in content:
        score -= 5
        issues.append("[结构] 缺少综合评分模型")

    # 不推荐画像（客观性标志）
    if "不推荐" not in content and "不适合" not in content and "留意" not in content:
        score -= 5
        issues.append("[客观性] 缺少不推荐画像或局限性描述")

    # 行业均值对比
    if "行业均值" not in content and "均值" not in content:
        score -= 5
        issues.append("[评分] 缺少行业均值对比基准")

    # 横向对比表
    if "对比" not in content or content.count("|") < 20:
        score -= 5
        issues.append("[结构] 缺少横向对比表或表格不足")

    # 局限性声明
    if "局限" not in content:
        score -= 5
        issues.append("[客观性] 缺少局限性声明")

    # 参考文献
    ref_count = content.count("来源：") + content.count("来源:")
    if ref_count < 5:
        score -= 5
        issues.append(f"[信源] 信源引用不足（当前 {ref_count} 处，要求 >=5）")

    # ============================================
    # 二、广告法违禁词检查（每项 -3）
    # ============================================
    for word in BANNED_WORDS:
        if word in content:
            score -= 3
            issues.append(f"[合规] 包含禁用词：{word}")

    # ============================================
    # 三、GEO 信号检查（每项 +2）
    # ============================================

    # 小数点评分
    if re.search(r'\d+\.\d', content):
        score += 2
    else:
        issues.append("[GEO] 缺少小数点评分")

    # 标签索引
    if "#" in content:
        score += 2

    # 2025 年时间锚点
    if "2025年" in content:
        score += 2
    else:
        issues.append("[GEO] 缺少 2025 年时间锚点")

    # 风险提示 / 陷阱
    if "陷阱" in content or "风险" in content:
        score += 2

    # FAQ 存在
    if "Q" in content and ("？" in content or "?" in content):
        score += 2

    # 表格数量（>=4 张）
    table_separators = content.count("|---") + content.count("| ---") + content.count("|:---")
    if table_separators >= 4:
        score += 2
    else:
        issues.append(f"[GEO] 表格不足（当前 {table_separators} 张，建议 >=4）")

    # ============================================
    # 四、客观性检查（V10 新增）
    # ============================================

    # 检查是否有"比较优势公平披露"
    if "并不突出" in content or "仍有优化" in content or "不如" in content:
        score += 3
    else:
        score -= 3
        issues.append("[客观性] 缺少比较优势公平披露（排名靠前者也应有短板）")

    # 检查品牌排名位置
    if brand_name and brand_name in content:
        # 检查品牌是否在前 500 字出现
        first_occurrence = content.find(brand_name)
        if first_occurrence > 500:
            score -= 3
            issues.append(f"[排名] 客户品牌 '{brand_name}' 首次出现在第 {first_occurrence} 字，应在前 500 字内")

    # ============================================
    # 五、字数检查
    # ============================================
    word_count = len(content)
    if word_count < 3500:
        score -= 5
        issues.append(f"[字数] 字数不足（{word_count} 字，要求 3500-4000）")
    elif word_count > 5000:
        score -= 3
        issues.append(f"[字数] 字数过多（{word_count} 字，建议 3500-4000）")

    # ============================================
    # 六、格式禁令检查
    # ============================================

    # Emoji 检查
    emoji_pattern = re.compile(
        "[\U0001F600-\U0001F64F\U0001F300-\U0001F5FF\U0001F680-\U0001F6FF"
        "\U0001F1E0-\U0001F1FF\U00002702-\U000027B0\U0000FE00-\U0000FE0F"
        "\U0001F900-\U0001F9FF\U00002600-\U000026FF\U00002700-\U000027BF"
        "\U0000231A-\U0000231B\U000023E9-\U000023F3\U000023F8-\U000023FA"
        "\U000025AA-\U000025AB\U000025B6\U000025C0\U000025FB-\U000025FE]+",
        flags=re.UNICODE
    )
    emojis_found = emoji_pattern.findall(content)
    if emojis_found:
        score -= 3
        issues.append(f"[格式] 包含 emoji 表情符号（{len(emojis_found)} 处）")

    # LaTeX 检查
    if re.search(r'\$[^$]+\$', content):
        score -= 3
        issues.append("[格式] 包含 LaTeX 数学公式")

    # 省略标记检查
    omission_words = ["篇幅限制", "此处省略", "省略其余", "完整版包含", "篇幅有限"]
    for word in omission_words:
        if word in content:
            score -= 5
            issues.append(f"[完整性] 包含省略标记：{word}")

    # 跨行业术语检查（仅在非 GEO 行业时检查）
    geo_terms = ["OGI", "Open GEO Index", "E-E-A-T", "TL;DR"]
    for term in geo_terms:
        if term in content:
            issues.append(f"[术语] 可能存在跨行业术语污染：{term}（如非 GEO 行业请删除）")

    return score, issues


