def split_components(raw: Any) -> list[str]:
    """把一个目录原始行业串拆成成分,顺序保留、去空白、去重复。"""
    text = "" if raw is None else str(raw)
    for sep in _SEPARATORS[1:]:
        text = text.replace(sep, _SEPARATORS[0])
    out: list[str] = []
    for part in text.split(_SEPARATORS[0]):
        part = part.strip()
        if part and part not in out:
            out.append(part)
    return out


def is_l1_key(value: Any) -> bool:
    """这个值是不是一个 L1 大类键(前端传回来的 chip 值)。"""
    return isinstance(value, str) and value in _L1_SET


def l1_keys_for(raw: Any) -> tuple[str, ...]:
    """一个原始串归属的 L1 大类(可能多个)。

    空串 → 空元组(**不是**「其他」:没填行业的媒体不该占任何 chip);
    有成分但一个都映射不到 → `("其他",)`。
    """
    comps = split_components(raw)
    if not comps:
        return ()
    keys: list[str] = []
    for comp in comps:
        for key in _COMPONENT_TO_L1.get(comp, ()):
            if key not in keys:
                keys.append(key)
    if not keys:
        return (OTHER_L1,)
    return tuple(k for k in L1_ORDER if k in keys)


def unmapped_components(raws: Iterable[Any]) -> list[str]:
    """目录全量原始串里**没有映射条目**的成分清单(完备性锁的判据)。

    返回空列表 = 完备。非空 = 有成分只能靠「其他」兜底,必须补映射。
    """
    missing: list[str] = []
    for raw in raws:
        for comp in split_components(raw):
            if comp not in _COMPONENT_TO_L1 and comp not in missing:
                missing.append(comp)
    return sorted(missing)


def raw_values_for_l1(raws: Iterable[Any], l1: str) -> list[str]:
    """目录里归属该 L1 的**原始串**集合 —— 筛选就按这个集合做 `= ANY(...)`。"""
    out: list[str] = []
    for raw in raws:
        if raw is None:
            continue
        text = str(raw)
        if not text:
            continue
        if l1 in l1_keys_for(text) and text not in out:
            out.append(text)
    return out


def facet_counts(pairs: Iterable[tuple[Any, int]]) -> list[dict]:
    """`(原始串, 该串的媒体数)` → `[{"key": L1, "count": n}, ...]`。

    - 数量为 0 的大类**不出现**(R2「空行业隐藏」:选了就是空结果的 chip 不该渲染);
    - 顺序按 `L1_ORDER`,切平台重算时 chip 不会乱跳;
    - 一个媒体的原始串命中多个大类时,每个大类各计一次(多标签 facet 的通行语义)。
    """
    totals: dict[str, int] = {}
    for raw, n in pairs:
        count = int(n or 0)
        if count <= 0:
            continue
        for key in l1_keys_for(raw):
            totals[key] = totals.get(key, 0) + count
    return [{"key": k, "count": totals[k]} for k in L1_ORDER if totals.get(k)]
