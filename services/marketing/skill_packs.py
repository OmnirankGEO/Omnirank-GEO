def seed_default_skill_packs() -> int:
    """幂等 seed 首版占位技能包(仅首次插入)。返回落库条数。
    [返工 R2] seed_mode=True:重启不覆盖热更新过的包内容/weight("改包不发版"保真)。"""
    n = 0
    for p in _DEFAULT_PACKS:
        try:
            marketing_db.upsert_skill_pack(
                pack_code=p["pack_code"], title=p["title"], content=p["content"],
                bind_signals=p["bind_signals"], weight=p["weight"], is_active=True,
                seed_mode=True)
            n += 1
        except Exception as e:  # noqa: BLE001
            logger.warning("[skill] seed %s 失败: %s", p["pack_code"], e)
    return n
