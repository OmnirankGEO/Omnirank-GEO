def assemble_system_prompt(*, awareness_stage: str = "unknown", rule_key: str = "",
                           task_hint: str = "") -> str:
    """装配军师 system prompt:世界观 + 禁承诺守卫 + 四资产 + 命中信号绑定的大师包(热加载)。"""
    parts = [WORLD_VIEW, PROMISE_GUARD_PROMPT, FOUR_ASSETS]

    # 按 bind_signals 匹配注入对应大师包(热加载 · 按 weight 排序)
    try:
        packs = marketing_db.list_active_skill_packs()
    except Exception as e:  # noqa: BLE001
        logger.warning("[skill] 技能包加载失败,只用底座: %s", e)
        packs = []

    matched = []
    for p in packs:
        binds = p.get("bind_signals_jsonb") or []
        if not binds or rule_key in binds or "*" in binds:
            matched.append(p)
    if matched:
        parts.append("【策划技能包(大师方法论 · 热加载)】")
        for p in matched:
            parts.append(f"— {p.get('title','')}:\n{p.get('content','')}")

    if awareness_stage and awareness_stage != "unknown":
        parts.append(f"【本案觉醒阶段】{awareness_stage}(施瓦茨5阶段 · 按阶段定信息角度)")
    if task_hint:
        parts.append(f"【本次任务】{task_hint}")
    return "\n\n".join(parts)


