-- 057 · 防守线派发的终态原因(#157)
-- =============================================================================
-- 派发遇到**不可重试**的异常(如题面超限导致的 pydantic ValidationError)时,
-- 今天走的是 `except Exception` → 归还 marker → 反复重试,直到 attempts 耗尽
-- 由 sweeper 退款。用户看到「一直没跑起来,最后退了钱」,**没有一句话说为什么**。
--
-- 加一列存终态原因,让前端/日志都看得见。
--
-- 🔴 **不复用 `reaped_reason`**:那是 sweeper 判死时写的原因。
--    派发终态与被 sweeper 收割是两件事(前者是"这单结构上跑不起来",
--    后者是"超时没人管"),挤进一个列以后就分不出该去查哪一头 ——
--    与 #147-B 里 `fallbackReason` 那次是同一种错误。
--
-- 🔴 **零 DML**:一列可空,不回填。NULL = 还没有终态原因。
--
-- 号段:056 归本单 §3.3 · **057 归 #157** · 下一空 = 058。
-- =============================================================================

